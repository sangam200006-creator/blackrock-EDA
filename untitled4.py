import pandas as pd

df = pd.read_csv('/content/blackrock_2022_Q1_holdings_value_esgrisk.csv')
display(df.head())

"""## Exploratory Data Analysis (EDA)

Let's start by understanding the structure of our data, checking for missing values, and getting some summary statistics.
"""

# Display basic information about the DataFrame, including data types and non-null values
df.info()

# Display descriptive statistics for numerical columns
display(df.describe())

# Check for missing values in each column
display(df.isnull().sum().sort_values(ascending=False))

# Display the number of unique values in each column
display(df.nunique().sort_values(ascending=False))

"""### Data Cleaning: Dropping Redundant Columns and Type Conversion"""

# Drop the 'Unnamed: 0' column as it appears to be an index
df = df.drop(columns=['Unnamed: 0'])

# Clean 'Shares Held or Principal Amt' and 'Market Value' columns
# Remove ',' and '$' characters and convert to numeric
df['Shares Held or Principal Amt'] = df['Shares Held or Principal Amt'].astype(str).str.replace(',', '', regex=False)
df['Shares Held or Principal Amt'] = pd.to_numeric(df['Shares Held or Principal Amt'], errors='coerce')

df['Market Value'] = df['Market Value'].astype(str).str.replace('$', '', regex=False).str.replace(',', '', regex=False)
df['Market Value'] = pd.to_numeric(df['Market Value'], errors='coerce')

# Display DataFrame info and head after cleaning
df.info()
display(df.head())